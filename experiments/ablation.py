#!/usr/bin/env python3
"""Ablation of the fusion rules and of the per-book gate, by CER of the fused output.

Each corpus uses only the specialist not trained on it.

Usage: python ablation.py [--output reports/ablation.md]
"""
import argparse
import collections
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from fusion import canon                                       # noqa: E402
from fusion.common import Acc, BagAcc, Rules, merge_line       # noqa: E402

csv.field_size_limit(10 ** 7)

# clean specialist per corpus; None = both serve
CLEAN = {'ocr17': ['kraken'], 'reichsanzeiger': ['calamari'],
         'porto': ['calamari', 'kraken'], 'impact': ['calamari', 'kraken'],
         'vesalainen_en': ['calamari', 'kraken'],   # neither engine saw it
         'goldseg': None}                     # goldseg is handled per corpus

VARIANTS = [
    ('production',      ''),
    ('no glyph rule',   '-glyph'),
    ('no space rule',   '-space'),
    ('no punctuation veto', '-veto_punct'),
    ('no hyphen veto',  '-veto_hyphen'),
    ('with digit veto', 'veto_digit'),
]


def load(ds):
    d = HERE / 'results' / ds
    pages = list(csv.DictReader(open(d / 'pages.csv', encoding='utf-8')))
    lines = collections.defaultdict(list)
    for r in csv.DictReader(open(d / 'lines.csv', encoding='utf-8')):
        lines[r['page_id']].append(r)
    for k in lines:
        lines[k].sort(key=lambda r: int(r['line_idx']))
    return pages, lines


def goldseg_corpus():
    return {r['id']: r['corpus'] for r in
            csv.DictReader(open(HERE / 'results/goldseg/pages.csv',
                                encoding='utf-8'))}


def measure(pages, lines, spec, rules, space, gate=0.0, key='book',
            only_corpus=None, corpus_map=None):
    """-> (Acc, BagAcc, stats). `gate` blocks rule 1 in the books whose
    ſ/(ſ+f) is below the threshold, measured on the specialist output only."""
    blocked = set()
    if gate > 0:
        count = collections.defaultdict(lambda: [0, 0])
        for p in pages:
            g = p.get(key) or '_'
            for r in lines.get(p['id'], []):
                count[g][0] += r[spec].count('ſ')
                count[g][1] += r[spec].count('f')
        blocked = {g for g, (s, f) in count.items()
                   if (s / (s + f) if (s + f) else 0.0) < gate}

    acc, bow = Acc(space=space), BagAcc(space=space)
    stats = {}
    for p in pages:
        if only_corpus and corpus_map and corpus_map.get(p['id']) != only_corpus:
            continue
        rows = lines.get(p['id'], [])
        if not rows:
            continue
        glyph = None if not blocked else ((p.get(key) or '_') not in blocked)
        fused = '\n'.join(
            merge_line(r['paddle'], r[spec], stats, glyph=glyph, rules=rules)
            if r[spec] else r['paddle'] for r in rows)
        acc.add(p['gold'], fused)
        bow.add(p['gold'], fused)
    return acc, bow, stats


def baseline(pages, lines, space, only_corpus=None, corpus_map=None):
    acc, bow = Acc(space=space), BagAcc(space=space)
    for p in pages:
        if only_corpus and corpus_map and corpus_map.get(p['id']) != only_corpus:
            continue
        if lines.get(p['id']):
            acc.add(p['gold'], p['paddle'] if 'paddle' in p else '')
    return acc, bow


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--output', default='reports/ablation.md')
    ap.add_argument('--gates', default='0.0,0.30',
                    help='thresholds for the per-book gate. The default is the '
                         'published pair; pass a wider list to measure how much '
                         'the 0.30 of the paper depends on being 0.30.')
    a = ap.parse_args()
    gates = sorted({float(x) for x in a.gates.split(',') if x.strip()})

    L = ['<!-- GENERATED by experiments/ablation.py. Manual edits are lost on the next run: change the script, not the .md. -->\n',
         '# Ablation of the fusion rules\n',
         '**Outcome** measure: each rule is toggled and the CER of the fused '
         'output is compared. It does not depend on defining "hit" and "damage" '
         'by position.\n',
         'Each corpus uses only the **clean** specialist (the one not trained '
         'on it). In `porto` and `impact` both are clean.\n']

    # goldseg, per corpus, line by line
    cmap = goldseg_corpus()
    pages, lines = load('goldseg')
    for corpus, spec in (('ocr17', 'kraken'), ('reichsanzeiger', 'calamari')):
        b, _ = baseline(pages, lines, 'line', corpus, cmap)
        L.append(f'\n## `goldseg` / {corpus}, specialist {spec} (clean), '
                 f'line by line\n')
        L.append('| configuration | CER | ΔCER vs Paddle | Δ vs production | '
                 '`f`→`ſ` swaps | spaces |')
        L.append('|---|--:|--:|--:|--:|--:|')
        prod = None
        for label, rule_spec in VARIANTS:
            acc, bow, st = measure(pages, lines, spec, Rules.from_text(rule_spec),
                                   'line', only_corpus=corpus, corpus_map=cmap)
            if prod is None:
                prod = acc.cer
            d1 = f'{(b.cer - acc.cer) / b.cer:+.2%}' if b.cer else '—'
            d2 = ('—' if label == 'production'
                  else f'{(prod - acc.cer) / prod:+.2%}')
            L.append(f'| {label} | {acc.cer:.4f} | {d1} | {d2} | '
                     f'{st.get("swapped_f_for_s", 0)} | '
                     f'{st.get("injected_space", 0)} |')
            print(f'  goldseg/{corpus:16} {label:20} CER {acc.cer:.4f}', flush=True)

    # vesalainen_en, line by line: both specialists are clean
    ves = HERE / 'results' / 'vesalainen_en' / 'pages.csv'
    if ves.exists():
        pages, lines = load('vesalainen_en')
        b, _ = baseline(pages, lines, 'line')
        for spec in CLEAN['vesalainen_en']:
            L.append(f'\n## `vesalainen_en`, specialist {spec} (clean), '
                     f'line by line\n')
            L.append('| configuration | CER | ΔCER vs Paddle | Δ vs production | '
                     '`f`→`ſ` swaps | spaces |')
            L.append('|---|--:|--:|--:|--:|--:|')
            prod = None
            for label, rule_spec in VARIANTS:
                acc, bow, st = measure(pages, lines, spec,
                                       Rules.from_text(rule_spec), 'line')
                if prod is None:
                    prod = acc.cer
                d1 = f'{(b.cer - acc.cer) / b.cer:+.2%}' if b.cer else '—'
                d2 = ('—' if label == 'production'
                      else f'{(prod - acc.cer) / prod:+.2%}')
                L.append(f'| {label} | {acc.cer:.4f} | {d1} | {d2} | '
                         f'{st.get("swapped_f_for_s", 0)} | '
                         f'{st.get("injected_space", 0)} |')
                print(f'  vesalainen_en/{spec:8} {label:20} '
                      f'CER {acc.cer:.4f}', flush=True)
    else:
        L.append('\n## `vesalainen_en`\n\nNot measured: '
                 '`results/vesalainen_en/pages.csv` does not exist.\n')
        print('  vesalainen_en: no data, section omitted', flush=True)

    # page-level datasets
    for ds in ('porto', 'impact', 'ocr17'):
        pages, lines = load(ds)
        base = Acc(space='page')
        for p in pages:
            if lines.get(p['id']):
                base.add(p['gold'], p['paddle'])
        for spec in CLEAN[ds]:
            L.append(f'\n## `{ds}`, specialist {spec}, per page\n')
            L.append('| configuration | CER | ΔCER vs Paddle | Δ vs production | '
                     '`f`→`ſ` swaps | spaces |')
            L.append('|---|--:|--:|--:|--:|--:|')
            prod = None
            for label, rule_spec in VARIANTS:
                acc, bow, st = measure(pages, lines, spec,
                                       Rules.from_text(rule_spec), 'page')
                if prod is None:
                    prod = acc.cer
                d1 = f'{(base.cer - acc.cer) / base.cer:+.2%}' if base.cer else '—'
                d2 = ('—' if label == 'production'
                      else f'{(prod - acc.cer) / prod:+.2%}')
                L.append(f'| {label} | {acc.cer:.4f} | {d1} | {d2} | '
                         f'{st.get("swapped_f_for_s", 0)} | '
                         f'{st.get("injected_space", 0)} |')
                print(f'  {ds}/{spec:10} {label:20} CER {acc.cer:.4f}', flush=True)

            # per-book gate, only where the column exists
            if pages and 'book' in pages[0]:
                L.append(f'\n**Per-work filter** (`--gates`), affects only the glyph rule (rule 1):\n')
                L.append('| threshold | CER | Δ vs no filter |')
                L.append('|---|--:|--:|')
                without = None
                for g in gates:
                    acc, _, _ = measure(pages, lines, spec, Rules(), 'page',
                                        gate=g)
                    if without is None:
                        without = acc.cer
                    d = '—' if g == 0 else f'{(without - acc.cer) / without:+.2%}'
                    L.append(f'| {g:.2f} | {acc.cer:.4f} | {d} |')
                    print(f'  {ds}/{spec:10} gate {g:.2f}          '
                          f'CER {acc.cer:.4f}', flush=True)

    out = HERE / a.output
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(f'\nwritten: {out}')


if __name__ == '__main__':
    main()
