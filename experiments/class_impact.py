#!/usr/bin/env python3
"""Fusion impact by error class: occurrences in the generalist output and in the
fused output, per corpus, with the specialist not trained on it.

Usage: python class_impact.py [--output reports/error_classes.md]
"""
import argparse
import collections
import csv
import sys
import unicodedata
from pathlib import Path

from rapidfuzz.distance import Levenshtein

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from fusion import canon                                       # noqa: E402
from fusion.common import DEFAULT, merge_line                   # noqa: E402

csv.field_size_limit(10 ** 7)

# specialist not trained on each corpus
CLEAN = {'ocr17': 'kraken', 'reichsanzeiger': 'calamari',
         'porto': 'calamari', 'impact': 'calamari'}


def stem(ch):
    return ''.join(c for c in unicodedata.normalize('NFD', ch)
                   if not unicodedata.combining(c))


def family(op, a, b):
    """Error class of one edit operation; non-target classes keep the net complete."""
    if op == 'delete':
        return 'missing space' if a == ' ' else 'missing character'
    if op == 'insert':
        return 'extra space' if b == ' ' else 'extra character'
    if {a, b} == {'f', 'ſ'} or {a, b} == {'f', 's'}:
        return 'f↔long s'
    if {a, b} == {'ſ', 's'}:
        return 'ſ↔s (spelling)'
    if a == ' ' or b == ' ':
        return 'substitution with space'
    if stem(a) == stem(b) and stem(a).strip():
        return 'diacritics'
    if a.lower() == b.lower():
        return 'case'
    return 'other substitution'


def count_families(g, h, fam):
    for tag, i1, i2, j1, j2 in Levenshtein.opcodes(g, h):
        if tag == 'equal':
            continue
        n = min(i2 - i1, j2 - j1) if tag == 'replace' else 0
        for k in range(n):
            fam[family('replace', g[i1 + k], h[j1 + k])] += 1
        for a in g[i1 + n:i2]:
            fam[family('delete', a, '')] += 1
        for b in h[j1 + n:j2]:
            fam[family('insert', '', b)] += 1


def run(ds, space, only_corpus=None, corpus_map=None, gate=0.0):
    """`gate` > 0 blocks rule 1 in books whose specialist ſ/(ſ+f) is below it."""
    d = HERE / 'results' / ds
    pages = list(csv.DictReader(open(d / 'pages.csv', encoding='utf-8')))
    lines = collections.defaultdict(list)
    for r in csv.DictReader(open(d / 'lines.csv', encoding='utf-8')):
        lines[r['page_id']].append(r)
    for k in lines:
        lines[k].sort(key=lambda r: int(r['line_idx']))
    spec = CLEAN[only_corpus or ds]

    blocked = set()
    if gate > 0:
        count = collections.defaultdict(lambda: [0, 0])
        for p in pages:
            g = p.get('book') or '_'
            for r in lines.get(p['id'], []):
                count[g][0] += r[spec].count('ſ')
                count[g][1] += r[spec].count('f')
        blocked = {g for g, (s, f) in count.items()
                   if (s / (s + f) if (s + f) else 0.0) < gate}

    before, after = collections.Counter(), collections.Counter()
    st = {}
    for p in pages:
        if only_corpus and corpus_map and corpus_map.get(p['id']) != only_corpus:
            continue
        rows = lines.get(p['id'])
        if not rows:
            continue
        glyph = None if not blocked else ((p.get('book') or '_') not in blocked)
        g = canon.canonicalize(p['gold'], space=space)
        base = '\n'.join(r['paddle'] for r in rows)
        fused = '\n'.join(
            merge_line(r['paddle'], r[spec], st, glyph=glyph, rules=DEFAULT)
            if r[spec] else r['paddle'] for r in rows)
        count_families(g, canon.canonicalize(base, space=space), before)
        count_families(g, canon.canonicalize(fused, space=space), after)
    return before, after, st, spec


ANNOTATION_NOTE = """
> **Note on the `ſ↔s` row.** In the page corpora (`porto`, `impact`) the rise of
> `ſ↔s` equals the number of rule firings outside the diplomatic stratum. Where
> the ground truth writes `s` and the print carries `ſ`, the rule restores the
> glyph and the edit is counted as an `ſ↔s` error. The rise therefore reflects
> ground truth that modernizes the glyph, not errors of the fusion.
>
> In `porto`, `ſ↔s` rises from 755 to 24,292, and the firings outside the
> diplomatic stratum are counted by `analyses/rule_precision_strict.py`. In the
> `goldseg` panels, whose ground truth is uniformly diplomatic, the same row
> changes by `+5` and `-1`.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--output', default='reports/error_classes.md')
    a = ap.parse_args()

    L = ['<!-- GENERATED by experiments/class_impact.py. '
         'Manual edits are lost on the next run: '
         'change the script, not the .md. -->\n',
         '# Impact of the fusion by error class\n',
         'The aggregate CER moves by 0.44 to 1.10 percentage points; the rules '
         'target two error classes. Below, for each class, the occurrences in '
         'the generalist output, the occurrences left after the fusion, and the '
         'net change.\n',
         'Each corpus uses the specialist not trained on it.\n',
         ANNOTATION_NOTE]

    cmap = {r['id']: r['corpus'] for r in
            csv.DictReader(open(HERE / 'results/goldseg/pages.csv',
                                encoding='utf-8'))}
    cases = [('goldseg', 'line', 'ocr17'), ('goldseg', 'line', 'reichsanzeiger'),
             ('porto', 'page', None), ('impact', 'page', None)]

    for ds, space, corpus in cases:
        before, after, st, spec = run(ds, space, corpus, cmap if corpus else None)
        label = f'{ds}/{corpus}' if corpus else ds
        ta, td = sum(before.values()), sum(after.values())
        L.append(f'\n## `{label}`, specialist {spec} ({space}-level comparison)\n')
        L.append(f'The glyph rule (rule 1) fired {st.get("swapped_f_for_s", 0)} times; '
                 f'the space rule (rule 2) injected {st.get("injected_space", 0)} spaces.\n')
        L.append('| error class | before | after | change |')
        L.append('|---|--:|--:|--:|')
        targets = ['f↔long s', 'ſ↔s (spelling)', 'missing space', 'extra space']
        for c in targets:
            va, vd = before[c], after[c]
            d = vd - va
            L.append(f'| **{c}** | {va} | {vd} | {d:+} |')
        others_before = sum(v for k, v in before.items() if k not in targets)
        others_after = sum(v for k, v in after.items() if k not in targets)
        L.append(f'| other classes | {others_before} | {others_after} | '
                 f'{others_after - others_before:+} |')
        L.append(f'| **total edits** | **{ta}** | **{td}** | '
                 f'**{td - ta:+}** ({(td - ta) / ta * 100:+.1f}%) |')
        print(f'{label:24} {spec:9} f↔s {before["f↔long s"]:6} -> '
              f'{after["f↔long s"]:6} | total {ta} -> {td}', flush=True)

    out = HERE / a.output
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(f'\nwritten: {out}')


if __name__ == '__main__':
    main()
