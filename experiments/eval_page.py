#!/usr/bin/env python3
"""Compares all systems on the page datasets, with `canon` and whitespace collapse.

The fine-tuned row comes from another inference path (`paddleocr.TextRecognition`).

Usage: python eval_page.py --datasets porto,impact [--output reports/page_results.md]
"""
import argparse
import collections
import csv
import json
import sys
from pathlib import Path

from rapidfuzz.distance import Levenshtein

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from fusion import canon                                       # noqa: E402
from fusion.common import Acc, BagAcc, Rules, merge_line       # noqa: E402

csv.field_size_limit(10 ** 7)
FT = HERE / 'finetune'
# slug of the fine-tuned model inside finetune/predictions/
FT_SLUG = 'test_3__sem_RecAug'


class LongS:
    def __init__(self):
        self.gold = self.hyp = self.right = 0

    def add(self, g, h):
        self.gold += g.count('ſ')
        self.hyp += h.count('ſ')
        for tag, i1, i2, _, _ in Levenshtein.opcodes(g, h):
            if tag == 'equal':
                self.right += g[i1:i2].count('ſ')


def finetuned_pages(ds):
    """page_id -> text of the fine-tuned model, assembled in detection order.

    It comes from the fine-tune batch run: per-crop predictions in
    `finetune/predictions/<slug>__<ds>.jsonl`, order in
    `finetune/transfer/<ds>/lines.csv`.
    """
    pred = FT / 'predictions' / f'{FT_SLUG}__{ds}.jsonl'
    order = FT / 'transfer' / ds / 'lines.csv'
    if not pred.exists() or not order.exists():
        return {}
    txt = {}
    for l in open(pred, encoding='utf-8'):
        try:
            r = json.loads(l)
        except json.JSONDecodeError:
            continue
        txt[r['k']] = r['t']
    per_page = collections.defaultdict(list)
    for r in csv.DictReader(open(order, encoding='utf-8')):
        per_page[r['page_id']].append((int(r['order']), txt.get(r['path'], '')))
    return {k: '\n'.join(t for _, t in sorted(v)) for k, v in per_page.items()}


def evaluate(ds, rules):
    d = HERE / 'results' / ds
    pages = list(csv.DictReader(open(d / 'pages.csv', encoding='utf-8')))
    lines = collections.defaultdict(list)
    for r in csv.DictReader(open(d / 'lines.csv', encoding='utf-8')):
        lines[r['page_id']].append(r)
    for k in lines:
        lines[k].sort(key=lambda r: int(r['line_idx']))
    finetuned = finetuned_pages(ds)

    systems = ['paddle', 'paddle_ft3', 'calamari', 'kraken', 'kraken_cond2',
               'fusion_calamari', 'fusion_kraken']
    acc = {s: Acc(space='page') for s in systems}
    accd = {s: Acc(space='page', fold_s=True) for s in systems}
    bow = {s: BagAcc(space='page') for s in systems}
    ls = {s: LongS() for s in systems}
    stats = {'fusion_calamari': {}, 'fusion_kraken': {}}
    present = collections.Counter()

    for p in pages:
        rows = lines.get(p['id'], [])
        if not rows:
            continue
        t = {
            'paddle': p['paddle'],
            'paddle_ft3': finetuned.get(p['id'], ''),
            'calamari': '\n'.join(r['calamari'] for r in rows),
            'kraken': '\n'.join(r['kraken'] for r in rows),
            'kraken_cond2': p.get('kraken_standalone') or '',
        }
        for spec in ('calamari', 'kraken'):
            t[f'fusion_{spec}'] = '\n'.join(
                merge_line(r['paddle'], r[spec], stats[f'fusion_{spec}'],
                           rules = rules) if r[spec] else r['paddle']
                for r in rows)
        g = canon.canonicalize(p['gold'], space='page')
        for s in systems:
            if t[s].strip():
                present[s] += 1
            acc[s].add(p['gold'], t[s])
            accd[s].add(p['gold'], t[s])
            bow[s].add(p['gold'], t[s])
            ls[s].add(g, canon.canonicalize(t[s], space='page'))
    return len(pages), acc, accd, bow, ls, stats, present


LABEL = {'paddle': 'Paddle base',
         'paddle_ft3': 'PP-OCRv6 fine-tuned (test_3, other inference path)',
         'calamari': 'Calamari alone', 'kraken': 'Kraken alone',
         'kraken_cond2': 'Kraken condition 2 (own pipeline)',
         'fusion_calamari': '**Paddle + Calamari**',
         'fusion_kraken': '**Paddle + Kraken**'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--datasets', default='porto,impact,ocr17,reichsanzeiger')
    ap.add_argument('--output', default='reports/page_results.md')
    ap.add_argument('--rules', default='')
    a = ap.parse_args()
    rules = Rules.from_text(a.rules)

    L = ['<!-- GENERATED by experiments/eval_page.py. Manual edits are lost on the next run: change the script, not the .md. -->\n',
         '# Page datasets: all systems\n',
         'Comparison per **page** (the level at which the ground truth exists), '
         'crops from the **Paddle detector**, `canon` normalization with '
         'whitespace collapse, which is needed because the ground truth is in '
         'paragraphs and the hypothesis in lines.\n',
         '> The row of the fine-tuned model is not on the same footing as '
         'the others. It comes from the fine-tune batch run: crops built from '
         'the same boxes but resized to height 64, and inference by '
         '`paddleocr.TextRecognition` instead of the provider. We measured that '
         'this change of path moves the CER of the base model by ~10% relative. '
         'That is small next to the observed gap, but it is not zero.\n',
         f'Fusion rules: `{rules}`\n']

    for ds in a.datasets.split(','):
        n, acc, accd, bow, ls, stats, present = evaluate(ds, rules)
        base = acc['paddle']
        L.append(f'\n## `{ds}`, {n} pages\n')
        L.append('| system | CER | ΔCER | WER | ΔWER | BoW-F1 | folded CER | '
                 '`ſ` ratio | `ſ` recall |')
        L.append('|---|--:|--:|--:|--:|--:|--:|--:|--:|')
        for s in LABEL:
            if not acc[s].length or not present[s]:
                continue
            v = ls[s]
            ratio = f'{v.hyp / v.gold:.2f}×' if v.gold else '—'
            rec = f'{v.right / v.gold:.3f}' if v.gold else '—'
            dc = f'{(base.cer - acc[s].cer) / base.cer:+.2%}' if base.cer else '—'
            dw = f'{(base.wer - acc[s].wer) / base.wer:+.2%}' if base.wer else '—'
            L.append(f'| {LABEL[s]} | {acc[s].cer:.4f} | {dc} | {acc[s].wer:.4f} | '
                     f'{dw} | {bow[s].f1:.4f} | {accd[s].cer:.4f} | {ratio} | {rec} |')
        missing = [LABEL[s] for s in LABEL if acc[s].length and not present[s]]
        if missing:
            L.append(f'\n*Absent from this dataset: {", ".join(missing)}.*')
        L.append(f'\nEdits: Calamari '
                 f'{stats["fusion_calamari"].get("swapped_f_for_s", 0)} swaps / '
                 f'{stats["fusion_calamari"].get("injected_space", 0)} spaces · '
                 f'Kraken {stats["fusion_kraken"].get("swapped_f_for_s", 0)} / '
                 f'{stats["fusion_kraken"].get("injected_space", 0)}')
        print(f'{ds}: ok ({n} pages)')

    out = HERE / a.output
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(f'written: {out}')


if __name__ == '__main__':
    main()
